#!/usr/bin/env node
"use strict";
const fs = require("node:fs"), path = require("node:path"), crypto = require("node:crypto");
const root = path.resolve(__dirname, "..");
function render(registry) {
  return "// Generated by scripts/sync-landscape-registry.cjs; edit the JSON registry.\n" +
    "window.CC_LANDSCAPE_REGISTRY = " + JSON.stringify(registry, null, 2) + ";\n";
}
function versionScripts(html, generatedRegistry) {
  return html.replace(/(<script\b[^>]*\bsrc=["'])(\.\/js\/[^"']+)(["'])/g, (match, before, source, after) => {
    const relative = source.split('?')[0];
    const bytes = relative === './js/landscape-registry.js' ? generatedRegistry : fs.readFileSync(path.join(root, 'src', relative));
    const version = crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    return `${before}${relative}?v=${version}${after}`;
  });
}
function sync(check = false) {
  const registry = JSON.parse(fs.readFileSync(path.join(root, "config/phase8-landscapes.json"), "utf8"));
  if (!registry.contractVersion) throw new Error("Missing landscape contractVersion");
  for (const [id, stage] of Object.entries(registry.stages)) {
    if (!["approved", "integrated"].includes(stage.status)) continue;
    for (const [layer, spec] of Object.entries(stage.layers)) {
      const hash = crypto.createHash("sha256").update(fs.readFileSync(path.join(root, spec.validation))).digest("hex");
      if (spec.cacheKey !== hash.slice(0, 8)) throw new Error(`${id}/${layer}: cacheKey does not match image bytes; update only the changed layer's registry entry`);
    }
  }
  const file = path.join(root, "src/js/landscape-registry.js"), expected = render(registry);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== expected) throw new Error("Runtime registry is stale. Run node scripts/sync-landscape-registry.cjs");
  } else fs.writeFileSync(file, expected);
  const stageCatalog=require('./stage-catalog.cjs');
  const stageFile=path.join(root,'src/js/stage-catalog.js'),stageExpected=stageCatalog.render(stageCatalog.build(root));
  if(check){if(!fs.existsSync(stageFile)||fs.readFileSync(stageFile,'utf8')!==stageExpected)throw new Error('Stage catalog is stale. Run registry sync');}
  else fs.writeFileSync(stageFile,stageExpected);
  let runtimePageVersion;
  for (const page of ['src/index.html', 'src/dev.html']) {
    const file = path.join(root, page), current = fs.readFileSync(file, 'utf8');
    let versioned = versionScripts(current, expected);
    if (page === 'src/index.html') runtimePageVersion = crypto.createHash('sha256').update(versioned).digest('hex').slice(0, 12);
    else {
      const frame = /(<iframe\b[^>]*\bid="sharedRuntime"[^>]*\bsrc=")([^"]+)(")/;
      if (!frame.test(versioned)) throw new Error('Development runtime iframe is missing');
      versioned = versioned.replace(frame, `$1./index.html?host=phase7-development&amp;landscapes=phase8&amp;v=${runtimePageVersion}$3`);
    }
    if (check) {
      if (current !== versioned) throw new Error(`${page}: stale script versions. Run node scripts/sync-landscape-registry.cjs`);
    } else if (current !== versioned) fs.writeFileSync(file, versioned);
  }
}
if (require.main === module) {
  try { sync(process.argv.includes("--check")); console.log("Landscape registry synchronized."); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = {sync, render, versionScripts};
