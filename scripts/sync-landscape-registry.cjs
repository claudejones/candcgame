#!/usr/bin/env node
"use strict";
const fs = require("node:fs"), path = require("node:path"), crypto = require("node:crypto");
const root = path.resolve(__dirname, "..");
function render(registry) {
  return "// Generated by scripts/sync-landscape-registry.cjs; edit the JSON registry.\n" +
    "window.CC_LANDSCAPE_REGISTRY = " + JSON.stringify(registry, null, 2) + ";\n";
}
function sync(check = false) {
  const registry = JSON.parse(fs.readFileSync(path.join(root, "config/phase8-landscapes.json"), "utf8"));
  if (!registry.contractVersion) throw new Error("Missing landscape contractVersion");
  for (const [id, stage] of Object.entries(registry.stages)) {
    if (!["approved", "integrated"].includes(stage.status)) continue;
    for (const [layer, spec] of Object.entries(stage.layers)) {
      const hash = crypto.createHash("sha256").update(fs.readFileSync(path.join(root, spec.validation))).digest("hex");
      if (spec.cacheKey !== hash.slice(0, 8)) throw new Error(`${id}/${layer}: cacheKey does not match image bytes; update only the changed layer's registry entry`);
    }
  }
  const file = path.join(root, "src/js/landscape-registry.js"), expected = render(registry);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== expected) throw new Error("Runtime registry is stale. Run node scripts/sync-landscape-registry.cjs");
  } else fs.writeFileSync(file, expected);
}
if (require.main === module) {
  try { sync(process.argv.includes("--check")); console.log("Landscape registry synchronized."); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = {sync, render};
